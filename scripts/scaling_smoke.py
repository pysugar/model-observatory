"""Existing scaling chart interactions and separated Computer Use evidence."""
from playwright.sync_api import expect
from capability_smoke import csv_download


def check_scaling(page,data,output):
    page.locator('[data-panel="capabilities"]').click()
    page.select_option('#effortScalingTask','complex')
    page.select_option('#effortScalingFamily','all')
    chart=page.locator('#effortScalingChart')
    legend=lambda model:page.locator(f'#effortScalingLegend [data-scale-model="{model}"]')
    expect(page.locator('#effortScalingTitle')).to_have_text('各模型在已测推理档位下的成绩')
    expect(chart.locator('.scaling-dot')).to_have_count(44)
    legend('claude-opus-5-5').click()
    expect(chart).to_have_attribute('data-pinned','claude-opus-5-5')
    expect(legend('claude-opus-5-5')).to_have_attribute('aria-pressed','true')
    expect(page.locator('#effortScalingDetail')).to_contain_text('Claude Opus 5.5')
    active=chart.locator('[data-scale-series="claude-opus-5-5"]')
    expect(active.locator('path')).to_have_attribute('stroke-width','4')
    assert active.locator('circle').first.get_attribute('fill')==active.get_attribute('data-color')
    legend('claude-sonnet-5-5').hover()
    expect(chart).to_have_attribute('data-emphasis','claude-sonnet-5-5')
    expect(chart).to_have_attribute('data-pinned','claude-opus-5-5')
    expect(page.locator('#effortScalingDetail')).to_contain_text('Claude Opus 5.5')
    page.mouse.move(0,0)
    expect(chart).to_have_attribute('data-emphasis','claude-opus-5-5')
    legend('claude-sonnet-5-5').focus()
    expect(chart).to_have_attribute('data-emphasis','claude-sonnet-5-5')
    page.locator('#resetScalingHighlight').focus()
    expect(chart).to_have_attribute('data-emphasis','claude-opus-5-5')
    for key in ('Enter','Space'):
        legend('claude-sonnet-5-5').focus();page.keyboard.press(key)
        expect(chart).to_have_attribute('data-pinned','claude-sonnet-5-5')
        page.keyboard.press(key)
        expect(chart).to_have_attribute('data-pinned','')
        expect(chart).to_have_attribute('data-emphasis','')
    legend('claude-opus-5-5').click();legend('claude-opus-5-5').click()
    expect(chart).to_have_attribute('data-pinned','')
    expect(chart).to_have_attribute('data-emphasis','')
    page.select_option('#effortScalingModel','grok-4-7')
    path=chart.locator('[data-scale-series="grok-4-7"] path').get_attribute('d')
    assert path.count('M')==2, 'Grok missing medium must break line'
    expect(page.locator('#effortScalingDetail tr[data-effort="medium"]')).to_contain_text('无数据')
    expect(page.locator('#effortScalingDetail tr[data-effort="high"]')).to_contain_text('无可比相邻值')
    page.select_option('#effortScalingModel','gemini-4-argon')
    expect(page.locator('#effortScalingDetail')).to_contain_text('仅 1 个已测点')
    assert 'L' not in chart.locator('[data-scale-series="gemini-4-argon"] path').get_attribute('d')
    expect(chart.locator('[data-scale-series="gemini-4-argon"] .scaling-dot')).to_have_count(1)
    page.locator('#resetScalingHighlight').click()
    expect(chart).to_have_attribute('data-pinned','')
    page.select_option('#effortScalingTask','osworld2')
    expect(chart.locator('.scaling-dot')).to_have_count(15)
    assert chart.locator('.scaling-dot').evaluate_all("nodes=>nodes.every(n=>!n.parentElement.closest('button,[role=button]'))")
    point=chart.locator('[data-scale-rel="gpt-6-astra"][data-effort="high"]')
    point.focus();page.keyboard.press('Enter')
    expect(chart).to_have_attribute('data-pinned','gpt-6-astra')
    page.keyboard.press('Space')
    expect(chart).to_have_attribute('data-pinned','')
    expect(chart.locator('.scaling-dot[data-effort="non-reasoning"]')).to_have_count(0)
    for series in data['computer_use_evidence']['openaiSweep']['series']:
        for effort,score in zip(['low','medium','high','xhigh','max'],series['scores']):
            point=chart.locator(f'[data-scale-series="{series["modelId"]}"] [data-effort="{effort}"]')
            expect(point).to_have_attribute('data-score',str(score))
    page.select_option('#effortScalingModel','gpt-6-1-sol')
    expect(page.locator('#effortScalingDetail tr[data-effort="xhigh"]')).to_contain_text('-0.18 pp')
    expect(page.locator('#effortScalingDetail tr[data-effort="xhigh"]')).to_contain_text('+8.87%')
    expect(page.locator('#effortScalingDetail tr[data-effort="xhigh"]')).to_contain_text('$1.0466')
    expect(page.locator('#effortScalingScope')).to_contain_text('provider-reported')
    page.locator('#effortScalingCard').screenshot(path=str(output/'scaling-osworld-desktop.png'),style='.nav-shell{visibility:hidden!important}')
    rows=csv_download(page,'#exportEffortScaling')
    measured=[r for r in rows if r['low_score']]
    assert len(measured)==3
    assert all(r['metric']=='partial reward' and r['release']=='v2026.08.08' for r in rows)
    assert all(r['harness']==r['max_steps']==r['runs']==r['ci']=='' for r in rows)
    for r in rows:
        if not r['low_score']:
            assert r['source_url']=='' and r['provenance']=='未测'
    page.select_option('#effortScalingModel','gemini-4-argon')
    expect(page.locator('#effortScalingDetail')).to_contain_text('此口径暂无数据')
    expect(page.locator('#effortScalingDetail a')).to_have_count(0)
    assert chart.locator('[data-scale-series="gemini-4-argon"]').count()==0
    page.select_option('#effortScalingModel','claude-opus-5')
    expect(page.locator('#effortScalingDetail')).to_contain_text('此口径暂无数据')
    expect(page.locator('#computerUseMax')).to_contain_text('2026-09-10 全套')
    for r in data['computer_use_evidence']['anthropicMax']['rows']:
        row=page.locator(f'#computerUseMax tr[data-computer-model="{r["modelId"]}"]')
        expect(row).to_contain_text(str(r['partialRewardPct'])+'%')
        expect(row).to_contain_text(str(r['strictSuccessRatePct'])+'%')
        expect(row).to_contain_text('max · 单点')
    expect(page.locator('#computerUseMax')).to_contain_text('108 任务')
    expect(page.locator('#computerUseMax')).to_contain_text('5 次独立运行的均值')
    expect(page.locator('#computerUseMax')).to_contain_text('原文名称 OSWorld 2.0')
    expect(page.locator('#computerUseMax')).to_contain_text('原文名称 OSWorld 2.1')
    expect(page.locator('#computerUseGemini')).to_contain_text('69.2%')
    expect(page.locator('#computerUseGemini')).to_contain_text('3 次运行取最大值')
    expect(page.locator('#computerUseGemini')).to_contain_text('原生 effort 未核验')
    expect(page.locator('#computerUseGrok')).to_contain_text('未发现公开可核实成绩')
    expect(page.locator('#computerUseEvidence svg')).to_have_count(0)
    page.locator('#computerUseEvidence').screenshot(path=str(output/'computer-use-protocols-desktop.png'),style='.nav-shell{visibility:hidden!important}')
    page.select_option('#pitfallConfig','gpt-6-1-sol:xhigh')
    expect(page.locator('#pitfallObservedDetail')).to_contain_text('-0.18 pp')
    expect(page.locator('#pitfallObservedDetail')).to_contain_text('+8.87%')
    expect(page.locator('#pitfallObservedDetail')).to_contain_text('8.15%')
    expect(page.locator('#pitfallObservedDetail [data-alternative]')).to_have_count(1)
    page.select_option('#pitfallConfig','gpt-6-sol:max')
    expect(page.locator('#pitfallObservedDetail')).to_contain_text('+2.41 pp')
    expect(page.locator('#pitfallObservedDetail')).to_contain_text('77.22%')
    expect(page.locator('#pitfallObservedDetail')).to_contain_text('跨模型切换配置')
    page.select_option('#pitfallConfig','gpt-6-astra:low')
    expect(page.locator('#pitfallObservedDetail')).to_contain_text('+4.67 pp')
    expect(page.locator('#pitfallObservedDetail')).to_contain_text('71.74%')
    page.select_option('#pitfallConfig','gpt-6-astra:max')
    expect(page.locator('#pitfallObservedDetail')).to_contain_text('本组观测未发现同时更便宜且不低分的替代')
    for effort in ['low','medium','high','xhigh']:
        expect(page.locator(f'[data-observed-config="gpt-6-astra:{effort}"]')).to_contain_text('存在更优替代')
    page.select_option('#pitfallConfig','gpt-6-1-sol:xhigh')
    page.locator('#pitfallGuide').screenshot(path=str(output/'pitfalls-desktop.png'),style='.nav-shell{visibility:hidden!important}')
    for width in (390,320):
        touch=page.context.browser.new_page(viewport={'width':width,'height':844},has_touch=True)
        try:
            touch.goto(page.url)
            touch.locator('[data-panel="capabilities"]').tap()
            touch.select_option('#effortScalingTask','osworld2')
            button=touch.locator('#effortScalingLegend [data-scale-model="gpt-6-1-sol"]')
            button.tap()
            expect(touch.locator('#effortScalingChart')).to_have_attribute('data-pinned','gpt-6-1-sol')
            button.tap()
            expect(touch.locator('#effortScalingChart')).to_have_attribute('data-pinned','')
            button.tap();touch.locator('#resetScalingHighlight').tap()
            expect(touch.locator('#effortScalingChart')).to_have_attribute('data-pinned','')
            button.tap()
            touch.locator('#effortScalingCard').screenshot(path=str(output/f'scaling-osworld-touch-{width}.png'),style='.nav-shell{visibility:hidden!important}')
            touch.locator('#computerUseEvidence').screenshot(path=str(output/f'computer-use-protocols-{width}.png'),style='.nav-shell{visibility:hidden!important}')
            touch.locator('#pitfallGuide').screenshot(path=str(output/f'pitfalls-{width}.png'),style='.nav-shell{visibility:hidden!important}')
            assert touch.evaluate('document.documentElement.scrollWidth <= innerWidth'), 'Computer Use page overflow'
        finally: touch.close()
    page.select_option('#effortScalingTask','complex')
    page.locator('#resetScalingHighlight').click()
